"""Deterministic synthetic learners for future model/policy acceptance tests.

The simulator intentionally uses a conjunctive/nonlinear response process. A
future engine must not merely recover data generated by an identical predictor.
"""

from __future__ import annotations

import hashlib
import math
import random
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator


class StrictFrozenModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class SyntheticItem(StrictFrozenModel):
    item_id: str
    family_id: str
    difficulty: float = Field(ge=-4, le=4)
    skill_weights: dict[str, float]
    combination_mode: Literal["compensatory", "conjunctive"] = "conjunctive"
    reading_load: float = Field(default=0, ge=0, le=2)
    diagram_load: float = Field(default=0, ge=0, le=2)
    base_log_time: float = Field(default=4.0, ge=1, le=8)

    @model_validator(mode="after")
    def positive_skill_weights(self) -> "SyntheticItem":
        if not self.skill_weights or any(weight <= 0 for weight in self.skill_weights.values()):
            raise ValueError("synthetic items need positive skill weights")
        return self


class SyntheticLearner(StrictFrozenModel):
    learner_id: str
    skill_abilities: dict[str, float]
    reading_sensitivity: float = Field(default=0, ge=0, le=2)
    diagram_sensitivity: float = Field(default=0, ge=0, le=2)
    slip_rate: float = Field(default=0.08, ge=0, le=0.4)
    guess_rate: float = Field(default=0.18, ge=0, le=0.4)
    timing_noise: float = Field(default=0.25, ge=0, le=1)


class SyntheticAttempt(StrictFrozenModel):
    learner_id: str
    item_id: str
    family_id: str
    correct_probability: float
    correct: bool
    active_time_ms: int
    confidence: Literal["sure", "maybe", "guessed"]
    simulator_version: str = "conjunctive-mismatch-simulator.v1"


def _ability_components(
    learner: SyntheticLearner, item: SyntheticItem
) -> tuple[float, float]:
    values = [
        (learner.skill_abilities.get(skill_id, -1.5), weight)
        for skill_id, weight in item.skill_weights.items()
    ]
    weighted_mean = sum(value * weight for value, weight in values) / sum(
        weight for _, weight in values
    )
    weakest = min(value for value, _ in values)
    return weighted_mean, weakest


def correct_probability(learner: SyntheticLearner, item: SyntheticItem) -> float:
    mean, weakest = _ability_components(learner, item)
    if item.combination_mode == "conjunctive":
        effective_ability = 0.45 * mean + 0.55 * weakest
    else:
        effective_ability = mean
    nuisance = (
        item.reading_load * learner.reading_sensitivity
        + item.diagram_load * learner.diagram_sensitivity
    )
    latent = effective_ability - item.difficulty - 0.35 * nuisance
    base = 1 / (1 + math.exp(-1.35 * latent))
    probability = learner.guess_rate + (
        1 - learner.guess_rate - learner.slip_rate
    ) * base
    return min(max(probability, 0.001), 0.999)


def simulate_attempt(
    learner: SyntheticLearner,
    item: SyntheticItem,
    *,
    seed: int,
    presentation_index: int = 0,
) -> SyntheticAttempt:
    seed_material = (
        f"{seed}:{learner.learner_id}:{item.item_id}:{presentation_index}".encode()
    )
    stable_seed = int.from_bytes(hashlib.sha256(seed_material).digest()[:8], "big")
    rng = random.Random(stable_seed)
    probability = correct_probability(learner, item)
    correct = rng.random() < probability
    mean, _ = _ability_components(learner, item)
    load = (
        item.reading_load * learner.reading_sensitivity
        + item.diagram_load * learner.diagram_sensitivity
    )
    log_time = item.base_log_time + 0.28 * max(item.difficulty - mean, -1) + 0.12 * load
    seconds = rng.lognormvariate(log_time, learner.timing_noise)
    confidence_draw = rng.random()
    if probability >= 0.72 and confidence_draw < 0.8:
        confidence = "sure"
    elif probability <= 0.42 and confidence_draw < 0.65:
        confidence = "guessed"
    else:
        confidence = "maybe"
    return SyntheticAttempt(
        learner_id=learner.learner_id,
        item_id=item.item_id,
        family_id=item.family_id,
        correct_probability=probability,
        correct=correct,
        active_time_ms=max(250, round(seconds * 1000)),
        confidence=confidence,
    )


