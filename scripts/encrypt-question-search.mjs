#!/usr/bin/env node
import { readFile, writeFile, mkdir, rename, rm } from "node:fs/promises";
import { resolve, dirname, join, relative } from "node:path";
import { parseArgs } from "node:util";
import { randomBytes } from "node:crypto";
import { deriveSearchKey, encryptSearchBytes, sha256 } from "../lib/question-search/crypto.ts";
import { validateCorpus } from "../lib/question-search/engine.ts";

const { values } = parseArgs({ options: {
  corpus: { type: "string" }, assets: { type: "string" }, output: { type: "string" }, "password-file": { type: "string" }, benchmark: { type: "string" },
} });
if (!values.corpus || !values.assets || !values.output) throw new Error("Usage: node scripts/encrypt-question-search.mjs --corpus work/.../corpus.json --assets work/.../assets.json --output public/question-search/data --password-file /private/password.txt");
const password = values["password-file"] ? (await readFile(values["password-file"], "utf8")).trimEnd() : process.env.QUESTION_SEARCH_PASSWORD;
if (!password || password.length < 8) throw new Error("Supply a password of at least 8 characters through --password-file or QUESTION_SEARCH_PASSWORD.");
const corpusBytes = new Uint8Array(await readFile(values.corpus));
const corpus = JSON.parse(new TextDecoder().decode(corpusBytes));
validateCorpus(corpus);
const assets = JSON.parse(await readFile(values.assets, "utf8"));
if (assets.corpusVersion !== corpus.version) throw new Error("The asset map belongs to a different corpus.");
const output = resolve(values.output);
const temporary = `${output}.building-${randomBytes(4).toString("hex")}`;
const encryption = { name: "AES-GCM", kdf: "PBKDF2", hash: "SHA-256", iterations: 600000, salt: randomBytes(16).toString("base64") };
const key = await deriveSearchKey(password, encryption);
const indexPath = `index-${corpus.version}.bin`;
const context = path => `question-search/v1/${corpus.version}/${path}`;
await mkdir(join(temporary, "assets"), { recursive: true });
try {
  const encrypted = await encryptSearchBytes(corpusBytes, key, context(indexPath));
  await writeFile(join(temporary, indexPath), encrypted);
  const expected = new Map(corpus.questions.map(q => [q.image.path, q.image.hash]));
  const completed = new Set();
  for (const asset of assets.assets) {
    if (!/^assets\/[a-f0-9]{64}\.bin$/.test(asset.path) || !expected.has(asset.path) || completed.has(asset.path)) throw new Error("Invalid or duplicate asset-map entry.");
    const bytes = new Uint8Array(await readFile(asset.source));
    if (await sha256(bytes) !== expected.get(asset.path)) throw new Error(`Source image changed: ${asset.path}`);
    await writeFile(join(temporary, asset.path), await encryptSearchBytes(bytes, key, context(asset.path)));
    completed.add(asset.path);
  }
  if (completed.size !== expected.size) throw new Error("The asset map is missing question images.");
  const manifest = { schemaVersion: 1, version: corpus.version, count: corpus.questions.length, index: { path: indexPath, sha256: await sha256(encrypted), bytes: encrypted.length }, encryption };
  if (values.benchmark) {
    const bytes = new Uint8Array(await readFile(values.benchmark));
    await writeFile(join(temporary, "benchmark.bin"), await encryptSearchBytes(bytes, key, context("benchmark.bin")));
  }
  await writeFile(join(temporary, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  await mkdir(dirname(output), { recursive: true });
  // Replace only an earlier pack generated by this tool, never an arbitrary directory.
  try {
    const previous = JSON.parse(await readFile(join(output, "manifest.json"), "utf8"));
    if (previous.schemaVersion !== 1 || previous.encryption?.name !== "AES-GCM") throw new Error("Refusing to replace an unknown output directory.");
    await rm(output, { recursive: true });
  } catch (error) { if (error.code !== "ENOENT") throw error; }
  await rename(temporary, output);
  console.log(JSON.stringify({ output: relative(process.cwd(), output), count: corpus.questions.length, images: completed.size, indexBytes: encrypted.length, version: corpus.version }));
} catch (error) {
  await rm(temporary, { recursive: true, force: true });
  throw error;
}
